class FoodLogResult {
  final String foodName;
  final double calories;
  final double protein;
  final double carbs;
  final double fat;
  final String message;

  FoodLogResult({
    required this.foodName,
    required this.calories,
    required this.protein,
    required this.carbs,
    required this.fat,
    required this.message,
  });
}
